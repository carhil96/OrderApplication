BEGIN
  IF (SELECT COUNT(*) FROM orders) <> (SELECT COUNT(*) FROM orders WHERE customer_id IS NOT NULL)
     OR EXISTS (SELECT 1 FROM orders WHERE customer_id IS NULL) THEN
    RAISE EXCEPTION 'Customer backfill validation failed; orders.customer remains intact';
  END IF;
  IF (SELECT COUNT(*) FROM customers) <> (SELECT COUNT(DISTINCT customer COLLATE "C") FROM orders) THEN
    RAISE EXCEPTION 'Customer deduplication validation failed';
  END IF;
END $$;

