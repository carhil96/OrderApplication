BEGIN
  IF EXISTS (SELECT 1 FROM orders WHERE customer IS NULL OR customer ~ '^[[:space:]]*$') THEN
    RAISE EXCEPTION 'Cannot migrate orders: customer names cannot be empty or whitespace';
  END IF;
  IF EXISTS (SELECT 1 FROM orders WHERE created_at IS NULL) THEN
    RAISE EXCEPTION 'Cannot migrate orders: created_at contains NULL values';
  END IF;
  IF EXISTS (SELECT 1 FROM orders WHERE status NOT IN ('CREATED', 'DELIVERED')) THEN
    RAISE EXCEPTION 'Cannot migrate orders: unsupported order status found';
  END IF;
END $$;

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) COLLATE "C" NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uq_customers_name UNIQUE (name),
  CONSTRAINT ck_customers_name_not_blank CHECK (name ~ '[^[:space:]]')
);

